export const KECAMATAN_NAMES: string[] = KECAMATAN_LOCATIONS.map(loc => loc.name);

export function getOuFromKecamatan(kecamatanName: string): {
  ou: 'GRT' | 'TSA';
  regency: string;
} {
  const normalized = (kecamatanName || '').trim().toUpperCase();
  const found = KECAMATAN_LOCATIONS.find(
    (l) => l.name.toUpperCase() === normalized
  );
  if (found) {
    return { ou: found.ou, regency: found.regency };
  }
  return { ou: 'TSA', regency: 'TASIKMALAYA' };
}
